//! `kkernel kg init` and `kkernel kg hook` — initialization and hook management.

use std::io::{BufRead, ErrorKind, IsTerminal, Write};
use std::path::Path;

use super::types::{HookCommand, HookStatus, InitArgs};
use anyhow::{bail, Context, Result};

const DEFAULT_KHIVE_TOML: &str = r#"# .khive/config.toml — project KG configuration
# Committed to git. All collaborators use these settings.

[[engines]]
name = "default"
model = "all-minilm-l6-v2"
default = true
dims = 384
"#;

// Vocabulary caches are owned by pack management (ADR-020 §3), not init.
const DEFAULT_SCHEMA_YAML: &str = concat!(
    "format_version: \"2.0.0\"\n",
    "ontology_version: \"1.0.0\"\n",
    "khive_version: \"",
    env!("CARGO_PKG_VERSION"),
    "\"\nremotes: []\n",
);

const OLD_GITIGNORE_CONTENT: &str = "*\n!.gitignore\n!kg/\n!kg/**\nkg/.remote-cache/\nkg/.remote-cache/**\nkg/remotes/\n!khive.toml\n";
const GITIGNORE_CONTENT: &str = "*\n!.gitignore\n!kg/\n!kg/**\nkg/.remote-cache/\nkg/.remote-cache/**\nkg/remotes/\n!config.toml\n";

const PRE_COMMIT_HOOK: &str = r#"#!/usr/bin/env bash
# .khive/kg/hooks/pre-commit
# Generated by kkernel kg init.
# Runs KG validation on staged NDJSON files.
# Bypass with: git commit --no-verify

set -euo pipefail

staged=$(git diff --cached --name-only \
  | grep -E '^\.khive/kg/(entities|edges)\.ndjson$' || true)
if [ -z "$staged" ]; then
  exit 0
fi

kkernel kg validate
"#;

const CI_WORKFLOW: &str = r#"name: KG Validate
on:
  push:
    paths: [".khive/kg/**"]
  pull_request:
    paths: [".khive/kg/**"]

jobs:
  validate:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - name: Validate KG
        run: kkernel kg validate --format github
"#;

pub(super) fn cmd_init(args: InitArgs) -> Result<()> {
    cmd_init_with_hook_prompt(args, prompt_hook_install)
}

fn cmd_init_with_hook_prompt(
    args: InitArgs,
    prompt: impl FnOnce(&Path) -> Result<()>,
) -> Result<()> {
    if args.add_hooks {
        return hook_install(&args.repo);
    }

    let khive_dir = args.repo.join(".khive");
    let kg_dir = khive_dir.join("kg");
    let hooks_dir = kg_dir.join("hooks");
    let toml_path = khive_dir.join("config.toml");
    let legacy_path = khive_dir.join("khive.toml");
    let root_path = args.repo.join("khive.toml");

    // Refuse legacy files, directories and dangling symlinks before any
    // scaffolding is written. Reconciliation is an explicit operator choice.
    match std::fs::symlink_metadata(&legacy_path) {
        Ok(_) => bail!(
            "Legacy configuration {} is not a loader path; reconcile it with {} before running kg init",
            legacy_path.display(),
            toml_path.display()
        ),
        Err(error) if error.kind() == ErrorKind::NotFound => {}
        Err(error) => {
            return Err(error).with_context(|| format!("inspect {}", legacy_path.display()))
        }
    }

    if existing_config_file(&root_path)? {
        println!(
            "  Skipped {} (root config takes precedence)",
            toml_path.display()
        );
        println!("  Preserved {}", root_path.display());
    } else if existing_config_file(&toml_path)? {
        println!("  Skipped {} (already exists)", toml_path.display());
    } else {
        std::fs::create_dir_all(&khive_dir)
            .with_context(|| format!("create {}", khive_dir.display()))?;
        if create_default_config(&toml_path)? {
            println!("  Initialized {}", toml_path.display());
        } else {
            println!("  Skipped {} (already exists)", toml_path.display());
        }
    }

    std::fs::create_dir_all(&kg_dir).with_context(|| format!("create {}", kg_dir.display()))?;
    std::fs::create_dir_all(&hooks_dir)
        .with_context(|| format!("create {}", hooks_dir.display()))?;

    let schema_path = kg_dir.join("schema.yaml");
    if create_default_schema(&schema_path)? {
        println!("  Initialized {}", schema_path.display());
    } else {
        println!("  Skipped {} (already exists)", schema_path.display());
    }

    for name in &["entities.ndjson", "edges.ndjson"] {
        let path = kg_dir.join(name);
        if !path.exists() {
            std::fs::write(&path, "").with_context(|| format!("create {}", path.display()))?;
        }
    }

    let gitignore = khive_dir.join(".gitignore");
    update_gitignore(&gitignore)?;

    let hook_script = hooks_dir.join("pre-commit");
    if !hook_script.exists() {
        std::fs::write(&hook_script, PRE_COMMIT_HOOK)
            .with_context(|| format!("write {}", hook_script.display()))?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mut perms = std::fs::metadata(&hook_script)?.permissions();
            perms.set_mode(0o755);
            std::fs::set_permissions(&hook_script, perms)?;
        }
    }

    println!(
        "  Initialized .khive/kg/ (schema.yaml, entities.ndjson, edges.ndjson, hooks/pre-commit)"
    );

    if args.ci {
        let workflow_dir = args.repo.join(".github/workflows");
        std::fs::create_dir_all(&workflow_dir)
            .with_context(|| format!("create {}", workflow_dir.display()))?;
        let workflow_path = workflow_dir.join("kg-validate.yml");
        if !workflow_path.exists() {
            std::fs::write(&workflow_path, CI_WORKFLOW)
                .with_context(|| format!("write {}", workflow_path.display()))?;
            println!("  Generated {}", workflow_path.display());
        }
    }

    prompt(&args.repo)?;
    Ok(())
}

fn prompt_hook_install(repo: &Path) -> Result<()> {
    let stdin = std::io::stdin();
    if !stdin.is_terminal() {
        return Ok(());
    }
    let mut input = stdin.lock();
    let mut output = std::io::stdout();
    prompt_hook_install_with_io(repo, true, &mut input, &mut output)
}

fn prompt_hook_install_with_io<R: BufRead, W: Write>(
    repo: &Path,
    stdin_is_terminal: bool,
    input: &mut R,
    output: &mut W,
) -> Result<()> {
    if !stdin_is_terminal {
        return Ok(());
    }
    write!(output, "  Install pre-commit hook? [y/N]: ")
        .context("write hook installation prompt")?;
    output.flush().context("flush hook installation prompt")?;
    let mut answer = String::new();
    input
        .read_line(&mut answer)
        .context("read hook installation answer")?;
    let answer = answer.trim();
    if answer.eq_ignore_ascii_case("y") || answer.eq_ignore_ascii_case("yes") {
        hook_install(repo)?;
    }
    Ok(())
}

fn existing_config_file(path: &Path) -> Result<bool> {
    let metadata = match std::fs::symlink_metadata(path) {
        Ok(metadata) => metadata,
        Err(error) if error.kind() == ErrorKind::NotFound => return Ok(false),
        Err(error) => return Err(error).with_context(|| format!("inspect {}", path.display())),
    };
    let is_file = if metadata.file_type().is_symlink() {
        std::fs::metadata(path)
            .with_context(|| format!("resolve existing configuration {}", path.display()))?
            .is_file()
    } else {
        metadata.is_file()
    };
    if !is_file {
        bail!(
            "Configuration path {} is not a regular file",
            path.display()
        );
    }
    Ok(true)
}

fn create_default_config(path: &Path) -> Result<bool> {
    match khive_fs::atomic_create::create_only(path, |file| {
        file.write_all(DEFAULT_KHIVE_TOML.as_bytes())
    }) {
        Ok(true) => Ok(true),
        Ok(false) => {
            if !existing_config_file(path)? {
                bail!(
                    "Configuration path {} changed during initialization; rerun kg init",
                    path.display()
                );
            }
            Ok(false)
        }
        Err(error) => Err(error).with_context(|| format!("create {}", path.display())),
    }
}

fn create_default_schema(path: &Path) -> Result<bool> {
    match khive_fs::atomic_create::create_only(path, |file| {
        file.write_all(DEFAULT_SCHEMA_YAML.as_bytes())
    }) {
        Ok(true) => Ok(true),
        Ok(false) => {
            let metadata = std::fs::symlink_metadata(path)
                .with_context(|| format!("inspect {}", path.display()))?;
            if !metadata.is_file() {
                bail!("KG schema path {} is not a regular file", path.display());
            }
            Ok(false)
        }
        Err(error) => Err(error).with_context(|| format!("create {}", path.display())),
    }
}

fn update_gitignore(path: &Path) -> Result<()> {
    match khive_fs::atomic_create::create_only(path, |file| {
        file.write_all(GITIGNORE_CONTENT.as_bytes())
    }) {
        Ok(true) => Ok(()),
        Ok(false) => {
            // A link belongs to the operator. Do not follow it for migration.
            let metadata = std::fs::symlink_metadata(path)
                .with_context(|| format!("inspect {}", path.display()))?;
            if metadata.is_file()
                && std::fs::read(path).with_context(|| format!("read {}", path.display()))?
                    == OLD_GITIGNORE_CONTENT.as_bytes()
            {
                std::fs::write(path, GITIGNORE_CONTENT)
                    .with_context(|| format!("write {}", path.display()))?;
            }
            Ok(())
        }
        Err(error) => Err(error).with_context(|| format!("create {}", path.display())),
    }
}

pub(super) fn cmd_hook(cmd: HookCommand) -> Result<()> {
    match cmd {
        HookCommand::Install { repo } => hook_install(&repo),
        HookCommand::Uninstall { repo } => hook_uninstall(&repo),
        HookCommand::Status { repo } => hook_status(&repo),
    }
}

pub(super) fn hook_install(repo: &Path) -> Result<()> {
    let hook_script = repo.join(".khive/kg/hooks/pre-commit");
    let git_hook = repo.join(".git/hooks/pre-commit");

    if !hook_script.exists() {
        bail!(
            "Hook script not found: {}. Run `kkernel kg init` first.",
            hook_script.display()
        );
    }

    if let Some(parent) = git_hook.parent() {
        std::fs::create_dir_all(parent).with_context(|| format!("create {}", parent.display()))?;
    }

    if git_hook.exists() || git_hook.is_symlink() {
        std::fs::remove_file(&git_hook)
            .with_context(|| format!("remove existing {}", git_hook.display()))?;
    }

    #[cfg(unix)]
    {
        use std::os::unix::fs::symlink;
        let absolute_script = hook_script
            .canonicalize()
            .unwrap_or_else(|_| hook_script.clone());
        symlink(&absolute_script, &git_hook)
            .with_context(|| format!("create symlink {}", git_hook.display()))?;
    }

    #[cfg(not(unix))]
    {
        std::fs::copy(&hook_script, &git_hook)
            .with_context(|| format!("copy hook to {}", git_hook.display()))?;
    }

    println!(
        "  Installed: {} -> {}",
        git_hook.display(),
        hook_script.display()
    );
    Ok(())
}

fn hook_uninstall(repo: &Path) -> Result<()> {
    let git_hook = repo.join(".git/hooks/pre-commit");
    if git_hook.exists() || git_hook.is_symlink() {
        std::fs::remove_file(&git_hook)
            .with_context(|| format!("remove {}", git_hook.display()))?;
        println!("  Uninstalled: {}", git_hook.display());
    } else {
        println!("  No hook installed at {}", git_hook.display());
    }
    Ok(())
}

fn hook_status(repo: &Path) -> Result<()> {
    let git_hook = repo.join(".git/hooks/pre-commit");
    let symlink_exists = git_hook.exists() || git_hook.is_symlink();
    let symlink_target = if symlink_exists {
        std::fs::read_link(&git_hook)
            .ok()
            .map(|p| p.display().to_string())
    } else {
        None
    };
    let target_valid = symlink_target
        .as_deref()
        .map(|t| Path::new(t).exists())
        .unwrap_or(false);

    let status = HookStatus {
        symlink_exists,
        symlink_target,
        target_valid,
    };
    let json = serde_json::to_string(&status).expect("serialize HookStatus");
    println!("{json}");
    Ok(())
}

