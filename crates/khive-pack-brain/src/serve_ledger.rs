//! ADR-081 §4 cross-session serve ledger — brain-owned record of recall serves
//! and their scorer-assigned grades.
//!
//! Row creation (`record_serve`) implements the normative write side of the
//! ledger; `memory.recall` wires into it via `brain.record_serve` (ADR-081 §5,
//! #394) to stamp `served_by_profile_id` and append the ledger row off the
//! response path. The read side is consumed by `brain.feedback` /
//! `brain.auto_feedback` when a caller supplies `serve_ledger_id` (ADR-081 §6):
//! dedup by `(scorer_run_id, id)`, the `accounting_profile_id` zero-weight
//! fail-safe, and grade backfill.
use crate::sql::sql;

use khive_runtime::RuntimeError;
use khive_storage::types::{SqlStatement, SqlValue};
use khive_storage::{SqlAccess, SqlWriter};

pub use khive_brain_core::compute_query_class;
use khive_brain_core::ServeAttribution;

fn sql_err(context: &str, e: impl std::fmt::Display) -> RuntimeError {
    RuntimeError::internal_with_context(format!("serve ledger {context}"), e)
}

/// One row of `brain_serve_ledger` (ADR-081 §4 normative schema).
pub struct ServeLedgerRow {
    pub id: String,
    pub namespace: String,
    #[allow(dead_code)]
    pub consumer_kind: String,
    pub served_by_profile_id: Option<String>,
    pub resolved_profile_id: Option<String>,
    #[allow(dead_code)]
    pub resolved_at: Option<i64>,
    /// `COALESCE(served_by_profile_id, resolved_profile_id)` — generated by SQLite,
    /// read back here rather than recomputed, so a future change to the generated
    /// expression cannot silently diverge from what the fold gate reads.
    pub accounting_profile_id: Option<String>,
    /// The tri-state marker stamped at serve time (ADR-081 amendment), or
    /// `None` for a legacy row written before the column existed, or one
    /// where the marker was unrecognized.
    pub serve_attribution: Option<ServeAttribution>,
    pub target_id: String,
    #[allow(dead_code)]
    pub query_class: String,
    #[allow(dead_code)]
    pub query_raw: String,
    #[allow(dead_code)]
    pub served_at: i64,
    #[allow(dead_code)]
    pub grade: Option<String>,
    #[allow(dead_code)]
    pub graded_at: Option<i64>,
    /// The scorer run that last graded this row, if any — the dedup token.
    pub scorer_run_id: Option<String>,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) struct ServeLedgerInsert {
    pub id: String,
    pub target_id: String,
}

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub(crate) struct ServeLedgerBatchSummary {
    pub written: usize,
    pub skipped: usize,
}

#[allow(clippy::too_many_arguments)]
fn serve_ledger_insert_statement(
    row: &ServeLedgerInsert,
    namespace: &str,
    consumer_kind: &str,
    served_by_profile_id: Option<&str>,
    resolved_profile_id: Option<&str>,
    resolved_at: Option<i64>,
    query_class: &str,
    query_raw: &str,
    served_at: i64,
    serve_attribution: Option<&str>,
) -> SqlStatement {
    SqlStatement {
        sql: sql!("brain_serve_ledger_insert").into(),
        params: vec![
            SqlValue::Text(row.id.clone()),
            SqlValue::Text(namespace.to_string()),
            SqlValue::Text(consumer_kind.to_string()),
            served_by_profile_id
                .map(|s| SqlValue::Text(s.to_string()))
                .unwrap_or(SqlValue::Null),
            resolved_profile_id
                .map(|s| SqlValue::Text(s.to_string()))
                .unwrap_or(SqlValue::Null),
            resolved_at.map(SqlValue::Integer).unwrap_or(SqlValue::Null),
            SqlValue::Text(row.target_id.clone()),
            SqlValue::Text(query_class.to_string()),
            SqlValue::Text(query_raw.to_string()),
            SqlValue::Integer(served_at),
            serve_attribution
                .map(|s| SqlValue::Text(s.to_string()))
                .unwrap_or(SqlValue::Null),
        ],
        label: Some("brain_serve_ledger_insert".into()),
    }
}

#[allow(clippy::too_many_arguments)]
pub(crate) async fn record_serves(
    sql: &dyn SqlAccess,
    rows: &[ServeLedgerInsert],
    namespace: &str,
    consumer_kind: &str,
    served_by_profile_id: Option<&str>,
    resolved_profile_id: Option<&str>,
    resolved_at: Option<i64>,
    query_class: &str,
    query_raw: &str,
    served_at: i64,
    serve_attribution: Option<&str>,
) -> Result<ServeLedgerBatchSummary, RuntimeError> {
    if rows.is_empty() {
        return Ok(ServeLedgerBatchSummary::default());
    }

    let statements = rows
        .iter()
        .map(|row| {
            serve_ledger_insert_statement(
                row,
                namespace,
                consumer_kind,
                served_by_profile_id,
                resolved_profile_id,
                resolved_at,
                query_class,
                query_raw,
                served_at,
                serve_attribution,
            )
        })
        .collect();
    let mut writer = sql.writer().await?;
    let affected = writer.execute_batch(statements).await?;
    let written = usize::try_from(affected)
        .map_err(|_| sql_err("insert serve batch", "affected row count exceeds usize"))?;
    let skipped = rows.len().checked_sub(written).ok_or_else(|| {
        sql_err(
            "insert serve batch",
            format!(
                "affected row count {written} exceeds input count {}",
                rows.len()
            ),
        )
    })?;

    Ok(ServeLedgerBatchSummary { written, skipped })
}

/// Record a new serve row (the ADR-081 §4 write side). Returns `Ok(true)` when
/// the row was written, `Ok(false)` when an exact-key duplicate was tolerated
/// (the natural key `(namespace, target_id, query_class, served_at)` already
/// has a row — a duplicate drain of the same batch, not an error).
#[allow(clippy::too_many_arguments)]
pub async fn record_serve(
    sql: &dyn SqlAccess,
    id: &str,
    namespace: &str,
    consumer_kind: &str,
    served_by_profile_id: Option<&str>,
    resolved_profile_id: Option<&str>,
    resolved_at: Option<i64>,
    target_id: &str,
    query_class: &str,
    query_raw: &str,
    served_at: i64,
    serve_attribution: Option<&str>,
) -> Result<bool, RuntimeError> {
    let rows = [ServeLedgerInsert {
        id: id.to_string(),
        target_id: target_id.to_string(),
    }];
    let summary = record_serves(
        sql,
        &rows,
        namespace,
        consumer_kind,
        served_by_profile_id,
        resolved_profile_id,
        resolved_at,
        query_class,
        query_raw,
        served_at,
        serve_attribution,
    )
    .await?;
    Ok(summary.written == 1)
}

/// Fetch a serve ledger row by id.
pub async fn get_serve_row(
    sql: &dyn SqlAccess,
    id: &str,
) -> Result<Option<ServeLedgerRow>, RuntimeError> {
    let mut reader = sql.reader().await?;
    let row = reader
        .query_row(SqlStatement {
            sql: sql!("brain_serve_ledger_row").into(),
            params: vec![SqlValue::Text(id.to_string())],
            label: Some("brain_serve_ledger_get".into()),
        })
        .await?;

    let Some(row) = row else {
        return Ok(None);
    };

    Ok(Some(ServeLedgerRow {
        id: row
            .text("id")
            .map(str::to_owned)
            .map_err(|_| sql_err("read row", "missing id column"))?,
        namespace: row
            .text("namespace")
            .map(str::to_owned)
            .map_err(|_| sql_err("read row", "missing namespace column"))?,
        consumer_kind: row
            .text("consumer_kind")
            .map(str::to_owned)
            .map_err(|_| sql_err("read row", "missing consumer_kind column"))?,
        served_by_profile_id: row.text_or_none("served_by_profile_id").map(str::to_owned),
        resolved_profile_id: row.text_or_none("resolved_profile_id").map(str::to_owned),
        resolved_at: row.i64_or_none("resolved_at"),
        accounting_profile_id: row.text_or_none("accounting_profile_id").map(str::to_owned),
        serve_attribution: ServeAttribution::from_column(row.text_or_none("serve_attribution")),
        target_id: row
            .text("target_id")
            .map(str::to_owned)
            .map_err(|_| sql_err("read row", "missing target_id column"))?,
        query_class: row
            .text("query_class")
            .map(str::to_owned)
            .map_err(|_| sql_err("read row", "missing query_class column"))?,
        query_raw: row
            .text("query_raw")
            .map(str::to_owned)
            .map_err(|_| sql_err("read row", "missing query_raw column"))?,
        served_at: row
            .i64("served_at")
            .map_err(|_| sql_err("read row", "missing served_at column"))?,
        grade: row.text_or_none("grade").map(str::to_owned),
        graded_at: row.i64_or_none("graded_at"),
        scorer_run_id: row.text_or_none("scorer_run_id").map(str::to_owned),
    }))
}

/// Backfill the grade inside the scorer claim + fold + event transaction.
/// A failed write rolls back the dedup claim, leaving the run retryable.
pub(crate) async fn backfill_grade_on_writer(
    writer: &mut dyn SqlWriter,
    id: &str,
    grade: &str,
    graded_at_us: i64,
    scorer_run_id: &str,
) -> Result<(), RuntimeError> {
    let affected = writer
        .execute(SqlStatement {
            sql: sql!("brain_serve_ledger_backfill_grade").into(),
            params: vec![
                SqlValue::Text(grade.to_string()),
                SqlValue::Integer(graded_at_us),
                SqlValue::Text(scorer_run_id.to_string()),
                SqlValue::Text(id.to_string()),
            ],
            label: Some("brain_serve_ledger_backfill_grade".into()),
        })
        .await?;
    if affected != 1 {
        return Err(RuntimeError::Internal(format!(
            "serve ledger backfill grade: expected one row for {id:?}, updated {affected}"
        )));
    }
    Ok(())
}

/// Outcome of resolving a `(scorer_run_id, serve_ledger_id)` pair against the
/// ledger, before the fold gate runs.
pub enum ServeLedgerResolution {
    /// Row found with matching namespace, target, and requested attribution.
    /// `already_graded` is a non-atomic shortcut for a same-run replay; the
    /// atomic scorer claim remains authoritative for concurrent submissions.
    /// Carries the accounting profile id to fold under, or `None` if unresolved (the
    /// caller must force a zero-weight fold — ADR-081 §4 fail-safe) — unless
    /// `serve_attribution` is the stored `unspecified` marker, which keeps the
    /// legacy binding/default fallback permitted instead of forcing zero.
    Found {
        already_graded: bool,
        accounting_profile_id: Option<String>,
        serve_attribution: Option<ServeAttribution>,
    },
    /// No row exists for `serve_ledger_id`.
    NotFound,
}

/// Resolve a `(scorer_run_id, serve_ledger_id)` pair against the ledger.
pub async fn resolve(
    sql: &dyn SqlAccess,
    serve_ledger_id: &str,
    scorer_run_id: &str,
    namespace: &str,
    target_id: &str,
    requested_profile_id: Option<&str>,
) -> Result<ServeLedgerResolution, RuntimeError> {
    let Some(row) = get_serve_row(sql, serve_ledger_id).await? else {
        return Ok(ServeLedgerResolution::NotFound);
    };
    // Validate before the AlreadyGraded shortcut: a replay with a different
    // target or attribution must not be reported as a successful no-op.
    if row.namespace != namespace || row.target_id != target_id {
        return Err(RuntimeError::InvalidInput(format!(
            "serve_ledger_id {serve_ledger_id:?} does not match feedback namespace and target_id"
        )));
    }
    let conflicting_profile = requested_profile_id
        .zip(row.accounting_profile_id.as_deref())
        .filter(|(requested, accounting)| requested != accounting);
    if let Some((requested, accounting)) = conflicting_profile {
        return Err(RuntimeError::InvalidInput(format!(
            "served_by_profile_id {requested:?} does not match serve_ledger_id {serve_ledger_id:?} accounting_profile_id {accounting:?}"
        )));
    }
    Ok(ServeLedgerResolution::Found {
        already_graded: row.scorer_run_id.as_deref() == Some(scorer_run_id),
        accounting_profile_id: row.accounting_profile_id,
        serve_attribution: row.serve_attribution,
    })
}

