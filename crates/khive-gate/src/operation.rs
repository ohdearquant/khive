//! Reviewed caller-requested effects for the built-in write restriction.
//!
//! Read permits existing incidental audit/cache/maintenance effects; it is not
//! a storage-level read-only right. See `docs/api/operation-access.md`.

/// Revision of the reviewed classification contract, included in policy identity.
/// Bump whenever a classification or the allowed-read contract changes.
pub const OPERATION_CLASSIFIER_VERSION: &str = "domain-effects-v5";

/// Strongest caller-requested effect of a reviewed operation.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum OperationAccess {
    /// Retrieval or calculation with existing incidental effects.
    Read,
    /// Domain mutation, control change, explicit maintenance, or external effect.
    Write,
}

