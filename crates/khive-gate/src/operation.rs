/// Classify an exact registered or pseudo-verb name. No prefix/category inference.
/// A restricting gate must deny `None`, just as it denies explicit Write.
pub fn classify_operation(verb: &str) -> Option<OperationAccess> {
    CLASSIFIED_OPERATIONS
        .binary_search_by_key(&verb, |(name, _)| *name)
        .ok()
        .map(|index| CLASSIFIED_OPERATIONS[index].1)
}
